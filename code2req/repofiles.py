"""Which files of a repository are the system.

Every stage reads the repo through this list, so a file is either in for all
of them or out for all of them:
  - in a git repo, tracked files only: untracked and ignored files are local
    scratch (debug dumps, copies in tmp/, one-off scripts);
  - no generated code: protobuf/gRPC stubs, wire and other generators mark
    their output "Code generated ... DO NOT EDIT" or "@generated";
  - nothing matching --exclude.

Outside git every file under the root counts, minus the usual tool folders.
"""

from __future__ import annotations

import fnmatch
import logging
import os
import re
import subprocess
from dataclasses import dataclass, field

from code2req.surfaces import CODE_EXTS, SKIP_DIRS, WALK_SKIP_DIRS

logger = logging.getLogger(__name__)

# Names that are generated whatever their header says.
GENERATED_NAMES = ("*.pb.go", "*.pb.gw.go", "*_grpc.pb.go", "*_pb2.py", "*_pb2_grpc.py", "*_pb2.pyi",
                   "*.pb.ts", "*_pb.js", "*_pb.d.ts", "*.g.dart", "*.freezed.dart")
GENERATED_HEADER_RE = re.compile(
    r"Code generated .*DO NOT EDIT|@generated|Generated by the protocol buffer compiler|"
    r"auto-?generated.*do not (edit|modify)|DO NOT EDIT.*(generated|auto-?generated)", re.I)
HEADER_LINES = 10


@dataclass
class RepoFiles:
    files: list[str] = field(default_factory=list)  # repo-relative, forward slashes, sorted
    git: bool = False
    generated: list[str] = field(default_factory=list)
    untracked_code: int = 0  # code files on disk that git does not track

    def __post_init__(self) -> None:
        self._set = set(self.files)

    def __contains__(self, rel: str) -> bool:
        return rel in self._set

    def stats(self) -> dict:
        return {"git": self.git, "files": len(self.files), "generated_skipped": self.generated,
                "untracked_code_skipped": self.untracked_code}


def _git_files(repo_path: str, *args: str) -> list[str] | None:
    try:
        inside = subprocess.run(["git", "rev-parse", "--is-inside-work-tree"], cwd=repo_path,
                                capture_output=True, text=True)
        if inside.returncode != 0 or inside.stdout.strip() != "true":
            return None
        out = subprocess.run(["git", "ls-files", "-z", *args], cwd=repo_path, capture_output=True,
                             check=True).stdout
    except (OSError, subprocess.CalledProcessError) as e:
        logger.warning("git ls-files failed in %s (%s), walking the tree", repo_path, e)
        return None
    return sorted({p.decode("utf-8", errors="surrogateescape") for p in out.split(b"\0") if p})


def _walk(repo_path: str) -> list[str]:
    files = []
    for root, dirs, names in os.walk(repo_path):
        dirs[:] = sorted(d for d in dirs if d not in WALK_SKIP_DIRS
                         and (not d.startswith(".") or d in (".github", ".circleci", ".buildkite")))
        for n in sorted(names):
            files.append(os.path.relpath(os.path.join(root, n), repo_path).replace(os.sep, "/"))
    return files


def is_generated(repo_path: str, rel: str) -> bool:
    base = rel.rsplit("/", 1)[-1]
    if any(fnmatch.fnmatch(base, p) for p in GENERATED_NAMES):
        return True
    if os.path.splitext(base)[1].lower() not in CODE_EXTS:
        return False
    try:
        with open(os.path.join(repo_path, rel), encoding="utf-8", errors="replace") as f:
            head = [f.readline() for _ in range(HEADER_LINES)]
    except OSError:
        return False
    return any(GENERATED_HEADER_RE.search(line) for line in head)


def _excluded(rel: str, patterns: list[str] | None) -> bool:
    base = rel.rsplit("/", 1)[-1]
    return any(fnmatch.fnmatch(rel, p) or fnmatch.fnmatch(base, p) for p in patterns or [])


def list_repo_files(repo_path: str, exclude: list[str] | None = None) -> RepoFiles:
    repo_path = os.path.abspath(repo_path)
    tracked = _git_files(repo_path, "--cached")
    git = tracked is not None
    files = tracked if git else _walk(repo_path)
    files = [f for f in files if os.path.isfile(os.path.join(repo_path, f))
             and not any(p in SKIP_DIRS for p in f.split("/")[:-1]) and not _excluded(f, exclude)]
    generated = [f for f in files if is_generated(repo_path, f)]
    gen = set(generated)
    untracked = 0
    if git:
        others = _git_files(repo_path, "--others", "--exclude-standard") or []
        untracked = sum(os.path.splitext(f)[1].lower() in CODE_EXTS for f in others)
    out = RepoFiles(files=[f for f in files if f not in gen], git=git, generated=generated,
                    untracked_code=untracked)
    logger.info("repo files: %d (%s), %d generated skipped, %d untracked code files skipped",
                len(out.files), "git-tracked" if git else "walked", len(generated), untracked)
    return out
